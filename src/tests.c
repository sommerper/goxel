static void test_revolve(void)
{
    const uint8_t red[4] = {255, 0, 0, 255}, green[4] = {0, 255, 0, 255};
    const float center[3] = {0.5, 0.5, 0.5};
    volume_t *volume = volume_new();
    uint8_t c[4];

    // Profile in the XZ plane, revolved around Z through voxel (0, 0, 0).
    volume_set_at(volume, NULL, (int[]){0, 0, 0}, red);
    volume_set_at(volume, NULL, (int[]){3, 0, 1}, green);
    volume_revolve(volume, 2, center);

    volume_get_at(volume, NULL, (int[]){0, 0, 0}, c);
    TEST(memcmp(c, red, 4) == 0);
    volume_get_at(volume, NULL, (int[]){1, 0, 0}, c);
    TEST(c[3] == 0);
    volume_get_at(volume, NULL, (int[]){-3, 0, 1}, c);
    TEST(memcmp(c, green, 4) == 0);
    volume_get_at(volume, NULL, (int[]){0, -3, 1}, c);
    TEST(memcmp(c, green, 4) == 0);
    volume_get_at(volume, NULL, (int[]){2, 2, 1}, c);
    TEST(memcmp(c, green, 4) == 0);
    volume_get_at(volume, NULL, (int[]){0, 0, 1}, c);
    TEST(c[3] == 0);
    volume_get_at(volume, NULL, (int[]){3, 3, 1}, c);
    TEST(c[3] == 0);
    volume_delete(volume);
}

static bool has_voxel(const volume_t *volume, int x, int y, int z)
{
    uint8_t c[4];
    volume_get_at(volume, NULL, (int[]){x, y, z}, c);
    return c[3] != 0;
}

static void test_revolve_selection(void)
{
    const uint8_t white[4] = {255, 255, 255, 255};
    image_t *img = image_new();
    volume_t *volume = img->active_layer->volume;

    // A profile along X at z = 0 is selected, the voxel at z = 3 is not.
    // Revolve around Z, with the axis through the profile's -X end.
    volume_set_at(volume, NULL, (int[]){0, 0, 0}, white);
    volume_set_at(volume, NULL, (int[]){2, 0, 0}, white);
    volume_set_at(volume, NULL, (int[]){2, 0, 3}, white);
    img->selection_mask = volume_new();
    volume_set_at(img->selection_mask, NULL, (int[]){0, 0, 0}, white);
    volume_set_at(img->selection_mask, NULL, (int[]){2, 0, 0}, white);
    image_revolve_selection(img, 2, (int[]){-1, 0, 0}, 0, NULL);
    TEST(has_voxel(volume, -2, 0, 0));
    TEST(!has_voxel(volume, 1, 0, 0));
    TEST(has_voxel(volume, 2, 0, 3));
    TEST(!has_voxel(volume, -2, 0, 3));
    TEST(!has_voxel(img->selection_mask, 0, -2, 0));

    // Revolving again replaces the previous result: no growth, and the
    // -X result is gone when we switch to +X.
    image_revolve_selection(img, 2, (int[]){-1, 0, 0}, 0, NULL);
    TEST(!has_voxel(volume, -6, 0, 0));
    image_revolve_selection(img, 2, (int[]){1, 0, 0}, 0, NULL);
    TEST(has_voxel(volume, 4, 0, 0));
    TEST(!has_voxel(volume, -2, 0, 0));
    TEST(has_voxel(volume, 0, 0, 0));

    // After any other edit, the previous result is kept.
    volume_set_at(volume, NULL, (int[]){9, 9, 9}, white);
    image_revolve_selection(img, 2, (int[]){-1, 0, 0}, 0, NULL);
    TEST(has_voxel(volume, 4, 0, 0));
    TEST(has_voxel(volume, -2, 0, 0));
    image_delete(img);
}

static void test_revolve_symmetry(void)
{
    const uint8_t white[4] = {255, 255, 255, 255};
    image_t *img = image_new();
    volume_t *volume = img->active_layer->volume;

    // Nothing selected: the whole layer spins.  With Z symmetry around
    // z = 0, like the brush, voxels at z = 0 are mirrored to z = -1.
    volume_set_at(volume, NULL, (int[]){0, 0, 0}, white);
    volume_set_at(volume, NULL, (int[]){2, 0, 0}, white);
    image_revolve_selection(img, 2, (int[]){-1, 0, 0}, 1 << 2,
                            (float[]){0, 0, 0});
    TEST(has_voxel(volume, -2, 0, 0));
    TEST(has_voxel(volume, -2, 0, -1));
    TEST(has_voxel(volume, 0, 2, -1));
    TEST(!has_voxel(volume, 0, 2, 1));
    image_delete(img);
}

static void test_transform_selection(void)
{
    const uint8_t white[4] = {255, 255, 255, 255};
    // An L over x 0..1, y 0..2 is selected, the voxel at 5, 5, 5 is not.
    const int l[4][3] = {{0, 0, 0}, {1, 0, 0}, {0, 1, 0}, {0, 2, 0}};
    image_t *img = image_new();
    volume_t *volume = img->active_layer->volume;
    float rot[4][4] = MAT4_IDENTITY, flip[4][4] = MAT4_IDENTITY;
    int i, aabb[2][3];

    img->selection_mask = volume_new();
    for (i = 0; i < 4; i++) {
        volume_set_at(volume, NULL, l[i], white);
        volume_set_at(img->selection_mask, NULL, l[i], white);
    }
    volume_set_at(volume, NULL, (int[]){5, 5, 5}, white);
    mat4_irotate(rot, M_PI / 2, 0, 0, 1);

    // A quarter turn swaps the sides.
    image_transform_selection(img, rot, 0, NULL);
    volume_get_bbox(img->selection_mask, aabb, true);
    TEST(aabb[1][0] - aabb[0][0] == 3 && aabb[1][1] - aabb[0][1] == 2);
    TEST(has_voxel(volume, 5, 5, 5));

    // A half turn stays in place, four quarter turns get back to the start.
    image_transform_selection(img, rot, 0, NULL);
    TEST(has_voxel(volume, 1, 2, 0) && has_voxel(volume, 1, 0, 0));
    TEST(!has_voxel(volume, 0, 0, 0));
    image_transform_selection(img, rot, 0, NULL);
    image_transform_selection(img, rot, 0, NULL);
    for (i = 0; i < 4; i++) {
        TEST(has_voxel(volume, l[i][0], l[i][1], l[i][2]));
        TEST(has_voxel(img->selection_mask, l[i][0], l[i][1], l[i][2]));
    }
    TEST(!has_voxel(volume, 1, 1, 0));

    // A flip stays in place too.
    mat4_iscale(flip, -1, 1, 1);
    image_transform_selection(img, flip, 0, NULL);
    TEST(has_voxel(volume, 1, 2, 0) && !has_voxel(volume, 0, 2, 0));
    TEST(has_voxel(img->selection_mask, 1, 1, 0));
    TEST(has_voxel(volume, 5, 5, 5));
    image_delete(img);
}

static void test_stretch_symmetry(void)
{
    const uint8_t white[4] = {255, 255, 255, 255};
    volume_t *volume = volume_new();

    // With X symmetry around x = 0, only the new voxels get mirrored.
    volume_set_at(volume, NULL, (int[]){2, 0, 0}, white);
    volume_set_at(volume, NULL, (int[]){3, 0, 0}, white);
    volume_stretch(volume, (int[]){1, 0, 0}, 2, 1 << 0, (float[]){0, 0, 0});
    TEST(has_voxel(volume, 5, 0, 0));
    TEST(has_voxel(volume, -5, 0, 0));
    TEST(has_voxel(volume, -6, 0, 0));
    TEST(!has_voxel(volume, -3, 0, 0));
    TEST(!has_voxel(volume, -7, 0, 0));
    volume_delete(volume);
}

static void test_save_selection(void)
{
    const uint8_t white[4] = {255, 255, 255, 255};
    float box[4][4];
    int err;
    if (DEFINED(WIN32)) return; // Don't test on Windows for the moment!
    bbox_from_extents(box, VEC(1, 2, 3), 4, 5, 6);
    mat4_copy(box, goxel.image->selection_box);
    goxel.image->selection_mask = volume_new();
    volume_set_at(goxel.image->selection_mask, NULL, (int[]){40, 2, 3}, white);
    save_to_file(goxel.image, "/tmp/goxel_test.gox");
    image_delete(goxel.image);
    goxel.image = image_new();
    err = goxel_import_file("/tmp/goxel_test.gox", NULL);
    TEST(err == 0);
    TEST(memcmp(goxel.image->selection_box, box, sizeof(box)) == 0);
    TEST(has_voxel(goxel.image->selection_mask, 40, 2, 3));
    TEST(!has_voxel(goxel.image->selection_mask, 0, 0, 0));
    image_delete(goxel.image);
    goxel.image = image_new();
    sys_delete_file("/tmp/goxel_test.gox");
}

static void test_save_tool(void)
{
    const tool_t *tool = goxel.tool;
    painter_t painter = goxel.painter;
    int err;
    if (DEFINED(WIN32)) return; // Don't test on Windows for the moment!
    action_exec2(ACTION_tool_set_selection);
    goxel.painter.symmetry = 0b101;
    vec3_set(goxel.painter.symmetry_origin, 1.5, 2, -3);
    save_to_file(goxel.image, "/tmp/goxel_test.gox");
    action_exec2(ACTION_tool_set_brush);
    goxel.painter.symmetry = 0;
    vec3_set(goxel.painter.symmetry_origin, 0, 0, 0);
    err = goxel_import_file("/tmp/goxel_test.gox", NULL);
    TEST(err == 0);
    TEST(goxel.tool->id == TOOL_SELECTION);
    TEST(goxel.painter.symmetry == 0b101);
    TEST(vec3_equal(goxel.painter.symmetry_origin, VEC(1.5, 2, -3)));
    action_exec2(tool->action_idx);
    goxel.painter = painter;
    image_delete(goxel.image);
    goxel.image = image_new();
    sys_delete_file("/tmp/goxel_test.gox");
}

static void test_undo_keeps_active_layer(void)
{
    const uint8_t white[4] = {255, 255, 255, 255};
    image_t *img = goxel.image;
    layer_t *first = img->active_layer;
    int first_id = first->id;

    // Select the first layer after adding a second one, edit, then undo.
    image_add_layer(img, NULL);
    image_history_push(img);
    img->active_layer = first;
    volume_set_at(first->volume, NULL, (int[]){0, 0, 0}, white);
    image_history_push(img);
    image_undo(img);
    TEST(img->active_layer->id == first_id);
    TEST(!has_voxel(img->active_layer->volume, 0, 0, 0));
    image_delete(goxel.image);
    goxel.image = image_new();
}

